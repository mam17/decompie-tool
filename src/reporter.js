import fs from 'node:fs';
import path from 'node:path';
import { ensureDirSync, sanitizeFileName, info, success } from './utils.js';

export class Reporter {
  static saveReport(analysisResult, baseOutputDir = './output') {
    const targetName = sanitizeFileName(
      analysisResult.target?.fileName ||
      analysisResult.packageInfo?.package_name ||
      'target_analysis'
    );
    const timestamp = new Date().toISOString().replace(/[:.]/g, '-').slice(0, 19);
    const reportDir = path.resolve(baseOutputDir, `${targetName}_${timestamp}`);
    ensureDirSync(reportDir);

    // 1. Save metadata.json
    const metadataPath = path.join(reportDir, 'metadata.json');
    fs.writeFileSync(metadataPath, JSON.stringify(analysisResult, null, 2), 'utf8');

    // 2. Generate Markdown report
    const mdContent = Reporter.generateMarkdown(analysisResult);
    const mdPath = path.join(reportDir, 'analysis_report.md');
    fs.writeFileSync(mdPath, mdContent, 'utf8');

    // 3. Save class inventory if available
    if (analysisResult.classes && analysisResult.classes.length > 0) {
      const classesPath = path.join(reportDir, 'classes.json');
      fs.writeFileSync(classesPath, JSON.stringify(analysisResult.classes, null, 2), 'utf8');
    }

    success(`Report successfully saved to: ${reportDir}`);
    return {
      reportDir,
      metadataPath,
      mdPath
    };
  }

  static generateMarkdown(data) {
    const lines = [];
    const target = data.target || {};
    const pkg = data.packageInfo || {};
    const sec = data.security || {};

    lines.push(`# Reverse Engineering Report: ${target.fileName || 'Target'}`);
    lines.push(`Generated: ${new Date().toLocaleString()}`);
    lines.push(`Generated by: **tool_revert** (powered by REA MCP engine)`);
    lines.push('');

    // Target Overview
    lines.push('## 1. Target Overview');
    lines.push(`- **File Path**: \`${target.path || 'N/A'}\``);
    lines.push(`- **File Size**: ${target.sizeFormatted || 'N/A'}`);
    if (target.sha256) {
      lines.push(`- **SHA-256**: \`${target.sha256}\``);
    }
    if (pkg.package_name) {
      lines.push(`- **Package Name**: \`${pkg.package_name}\``);
      lines.push(`- **Version Code**: \`${pkg.version_code || 'N/A'}\``);
      lines.push(`- **Version Name**: \`${pkg.version_name || 'N/A'}\``);
      lines.push(`- **Min SDK**: \`${pkg.min_sdk || 'N/A'}\``);
      lines.push(`- **Target SDK**: \`${pkg.target_sdk || 'N/A'}\``);
    }
    if (target.isXapk && target.xapkDetails) {
      lines.push(`- **Container Format**: XAPK / APKM Bundle`);
      lines.push(`- **Primary APK Analyzed**: \`${target.xapkDetails.primaryApk}\``);
      lines.push(`- **Split APKs Count**: ${target.xapkDetails.splitApks?.length || 0}`);
      lines.push('');
      lines.push('### Included APKs in XAPK');
      lines.push('| APK Name | Size |');
      lines.push('| --- | --- |');
      for (const split of (target.xapkDetails.splitApks || [])) {
        lines.push(`| \`${split.name}\` | ${split.sizeFormatted} |`);
      }
    }
    lines.push('');

    // Security & Risks
    if (sec.findings && sec.findings.length > 0) {
      lines.push('## 2. Security Findings');
      for (const finding of sec.findings) {
        lines.push(`### [${finding.severity}] ${finding.title}`);
        lines.push(`${finding.description}`);
        lines.push('');
      }
    }

    // Permissions
    if (sec.dangerousPermissions && sec.dangerousPermissions.length > 0) {
      lines.push('## 3. Dangerous Permissions');
      for (const perm of sec.dangerousPermissions) {
        lines.push(`- \`${typeof perm === 'string' ? perm : perm.name}\``);
      }
      lines.push('');
    }

    // Exported Components
    if (sec.exportedComponents && sec.exportedComponents.length > 0) {
      lines.push('## 4. Exported Components (Attack Surface)');
      lines.push('| Component Type | Name | Permission Required |');
      lines.push('| --- | --- | --- |');
      for (const comp of sec.exportedComponents) {
        lines.push(`| ${comp.type} | \`${comp.name}\` | \`${comp.permission || 'None (Open)'}\` |`);
      }
      lines.push('');
    }

    // Detected SDKs
    if (data.detectedSdks && data.detectedSdks.length > 0) {
      lines.push('## 5. Detected Libraries & SDKs');
      for (const sdk of data.detectedSdks) {
        lines.push(`- ${sdk}`);
      }
      lines.push('');
    }

    // REA Agent Next Steps
    lines.push('## 6. Next Steps with REA Agent Skill');
    lines.push('To inspect deep implementation details of specific methods or classes:');
    lines.push('1. Open your AI agent with the `reverse-engineer-anything` skill.');
    lines.push(`2. Ask the agent: *"Dịch ngược logic của class <ClassName> trong file ${target.path}"*`);
    lines.push('3. The REA MCP tools (`inspect_android_class`, `decompile_jeb_item`, `trace_android_references`) will decompile the logic on demand.');
    lines.push('');

    return lines.join('\n');
  }
}
